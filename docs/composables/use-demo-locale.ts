import { useData } from 'vitepress'
import { computed } from 'vue'

export type DemoLocale = 'zh' | 'en'

export function useDemoLocale() {
  let localeIndexRef: { value: string } = { value: 'root' }
  try {
    const data = useData()
    if (data?.localeIndex) {
      localeIndexRef = data.localeIndex
    }
  } catch {
    // SSR or non-VitePress context
  }
  const isEn = computed(() => localeIndexRef?.value === 'en')
  const t = computed(() => (isEn.value ? en : zh))
  const format = (str: string, vars: Record<string, string | number>) => {
    return Object.entries(vars).reduce((s, [k, v]) => s.replace(`{{${k}}}`, String(v)), str)
  }
  /** 带当前 locale 的弹层配置，使 LayerFooter 的确认/取消等按钮显示对应语言 */
  const layerLocale = computed(() => ({ locale: isEn.value ? 'en' : 'zh-CN' }))
  const withLocale = <T extends Record<string, any>>(opts: T): T & { i18n: { locale: string } } =>
    ({ ...opts, i18n: { ...(opts.i18n ?? {}), ...layerLocale.value } })
  return { isEn, t, format, layerLocale, withLocale }
}

